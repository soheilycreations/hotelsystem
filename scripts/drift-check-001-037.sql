             then 'OK' else 'MISSING' end
      when 'column' then (
        select case when a.attname is null then 'MISSING'
                    when format_type(a.atttypid, a.atttypmod) = e.detail then 'OK'
                    else 'TYPE DIFFERS (production: ' || format_type(a.atttypid, a.atttypmod) || ')' end
        from (select 1) one
        left join pg_class c on c.relnamespace = 'public'::regnamespace and c.relkind = 'r'
                            and c.relname = split_part(e.obj, '.', 1)
        left join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
                                and a.attname = split_part(e.obj, '.', 2))
      when 'enum' then
        case when exists (select 1 from pg_enum v join pg_type t on t.oid = v.enumtypid
                          where t.typnamespace = 'public'::regnamespace
                            and t.typname = split_part(e.obj, '.', 1)
                            and v.enumlabel = split_part(e.obj, '.', 2))
             then 'OK' else 'MISSING' end
      when 'function' then
        case when exists (select 1 from pg_proc p where p.pronamespace = 'public'::regnamespace
                          and p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' = e.obj)
             then 'OK'
             when exists (select 1 from pg_proc p where p.pronamespace = 'public'::regnamespace
                          and p.proname = split_part(e.obj, '(', 1))
             then 'DIFFERENT ARGUMENTS (old version?)'
             else 'MISSING' end
      when 'trigger' then
        case when exists (select 1 from pg_trigger t
                          join pg_class c on c.oid = t.tgrelid
                          join pg_proc p on p.oid = t.tgfoid
                          where c.relnamespace = 'public'::regnamespace and not t.tgisinternal
                            and c.relname || ' → ' || p.proname || '()' = e.obj)
