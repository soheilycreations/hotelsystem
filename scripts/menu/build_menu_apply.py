#!/usr/bin/env python3
"""
MENU REBUILD — step 3: generate the update script from the confirmed plan.

  python3 scripts/menu/build_menu_apply.py data/menu_review.json \
      data/current_menu_export.csv scripts/menu/03-menu-apply.sql

The plan (menu_review.json, from build_menu_review.py) is embedded in the SQL
as data, so the script runs on its own in the Supabase SQL editor. The
export is only used to choose each new category's printer (kitchen / bar):
the station most of its existing items print to today.
"""
import csv
import json
import sys
from collections import Counter


def q(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def main():
    plan = json.load(open(sys.argv[1], encoding="utf-8"))
    export = list(csv.DictReader(open(sys.argv[2], encoding="utf-8-sig")))
    out = sys.argv[3]

    eff_station = {}
    for r in export:
        st = r["item_station"] if r["item_station"] not in ("", "null") else r["category_station"]
        eff_station[r["item_id"]] = st or "kitchen"
    cat_station_now = {r["category_id"]: r["category_station"] for r in export}

    # which old items land in which category
    votes = {}
    for it in plan["items"]:
        if it["action"] in ("MATCH", "KEEP") and it.get("old_id"):
            votes.setdefault(it["category"], Counter())[eff_station[it["old_id"]]] += 1

    cat_rows = []
    for c in plan["categories"]:
        if c["old_id"]:
            station = cat_station_now.get(c["old_id"], "kitchen")  # existing category keeps its printer
        else:
            v = votes.get(c["name"])
            station = v.most_common(1)[0][0] if v else "kitchen"
        cat_rows.append(f"    ({q(c['name'])}, {c['sort_order']}, {q(c['old_id'])}::uuid, {q(c['action'])}, {q(station)})")
    for name, cid in plan["internal_categories"].items():
        cat_rows.append(f"    ({q(name)}, null, {q(cid)}::uuid, 'INTERNAL', null)")

    item_rows = []
    for it in plan["items"]:
        a = it["action"]
        if a in ("MATCH", "NEW"):
            item_rows.append("    ({}, {}::uuid, {}, {}, {}, {}, {}, {})".format(
                q(a), q(it.get("old_id")), q(it["category"]), q(it["name"]),
                q(it["price"]), q(bool(it["visible"])), it["item_order"], q(it.get("description"))))
        elif a == "KEEP":
            item_rows.append("    ('KEEP', {}::uuid, {}, null, null, true, {}, null)".format(
                q(it["old_id"]), q(it["category"]), it.get("item_order") or 0))
        elif a == "HIDE":
            item_rows.append("    ('HIDE', {}::uuid, null, null, null, false, 0, null)".format(q(it["old_id"])))

    counts = Counter(i["action"] for i in plan["items"])
    visible_expected = sum(1 for i in plan["items"] if i["action"] in ("MATCH", "NEW") and i["visible"]) + counts["KEEP"]
    sql = TEMPLATE
    for k, v in {
        "__CATEGORIES__": ",\n".join(cat_rows),
        "__ITEMS__": ",\n".join(item_rows),
        "__N_MATCH__": str(counts["MATCH"]), "__N_NEW__": str(counts["NEW"]),
        "__N_KEEP__": str(counts["KEEP"]), "__N_HIDE__": str(counts["HIDE"]),
        "__N_VISIBLE__": str(visible_expected),
        "__N_INTERNAL__": str(len(plan["internal_untouched"])),
    }.items():
        sql = sql.replace(k, v)
    open(out, "w", encoding="utf-8").write(sql)
    print(f"wrote {out}: {len(cat_rows)} categories, {len(item_rows)} item rows "
          f"(MATCH {counts['MATCH']}, NEW {counts['NEW']}, KEEP {counts['KEEP']}, HIDE {counts['HIDE']})")


TEMPLATE = r"""-- ============================================================================
-- MENU REBUILD — step 3: apply the confirmed menu (one transaction)
-- ----------------------------------------------------------------------------
-- GENERATED by scripts/menu/build_menu_apply.py from data/menu_review.json —
-- edit the plan and regenerate rather than editing this file.
--
-- Run in the Supabase SQL editor AFTER migration 045.
-- DRY RUN (default, v_commit := false): makes every change, checks it, then
-- raises an error whose text is the report — that error is what rolls
-- everything back. Set v_commit := true and run again to apply.
--
-- Refuses to run (nothing changed) unless:
--   * menu_backup_20261024 exists and its copies are intact;
--   * migration 045 is applied (sort_order, description, is_archived);
--   * the live menu is still exactly what was backed up and exported on
--     24 Oct (otherwise the plan may be stale — re-run the backup and the
--     export and regenerate). This also stops it from running twice.
--
-- What it does — never deletes anything:
--   categories  rename/keep/create per the plan, with sort order; new ones
--               get the printer (kitchen/bar) most of their items use today.
--               Internal categories (Function Items, Staff Menu, Boss Site,
--               Party, Other) are left as they are — set v_internal_to_end
--               to true to move their tabs after the menu categories.
--   MATCH       existing item takes the new name, category, price, position,
--               description and visibility — same id, so past bills and
--               recipe links stay. "Price TBD" rows keep the old price and
--               are switched off.
--   NEW         inserted (price TBD -> Rs 0 and switched off).
--   KEEP        moved to Breakfast & Lunch / Other, name and price unchanged.
--   HIDE        archived (is_archived) and switched off.
--   Every moved item keeps printing where it prints today: if its new
--   category prints elsewhere, the item gets its own station setting.
-- Self-checks before finishing: recipe links unchanged, internal items
-- unchanged, no item deleted, counts as planned.
-- ============================================================================
do $$
declare
  -- ======================== EDIT THESE SETTINGS ============================
  v_commit          boolean := false;  -- false = dry run (rolls back), true = apply
  v_internal_to_end boolean := false;  -- true = internal category tabs after the menu ones
  -- =========================================================================
  c_backup constant text := 'menu_backup_20261024';
  r record;
  v_md5 text;
  v_md5_live text;
  v_cols text;
  v_bad text := '';
  v_report text := '';
  v_n int;
  v_items_before int;
  v_recipe_md5 text;
  v_internal_md5 text;
begin
  -- -------------------------------------------------------- safety checks
  if not exists (select 1 from pg_namespace where nspname = c_backup) then
    raise exception 'REFUSED: % not found — run scripts/menu/01-menu-backup.sql first.', c_backup;
  end if;
  if not exists (select 1 from information_schema.columns where table_schema = 'public'
                 and table_name = 'menu_items' and column_name = 'is_archived') then
    raise exception 'REFUSED: migration 045 is not applied (menu_items.is_archived missing).';
  end if;

  for r in execute format('select table_name, md5 from %I._manifest', c_backup) loop
    -- backup copy intact?
    execute format('select md5(coalesce(string_agg(x::text, E''\n'' order by x::text), '''')) from %I.%I x',
                   c_backup, r.table_name) into v_md5;
    if v_md5 <> r.md5 then
      v_bad := v_bad || format(E'\n  backup copy of %s is damaged', r.table_name);
    end if;
    -- live table unchanged since the backup? (compared on the backup's columns)
    select string_agg(format('%I', column_name), ', ' order by ordinal_position) into v_cols
    from information_schema.columns where table_schema = c_backup and table_name = r.table_name;
    execute format('select md5(coalesce(string_agg(x::text, E''\n'' order by x::text), '''')) '
                   'from (select %s from public.%I) x', v_cols, r.table_name) into v_md5_live;
    if v_md5_live <> r.md5 then
      v_bad := v_bad || format(E'\n  public.%s changed since the backup on 24 Oct', r.table_name);
    end if;
  end loop;
  if v_bad <> '' then
    raise exception E'REFUSED — nothing changed:%\nIf the menu was edited since 24 Oct: rename the backup schema, run 01-menu-backup.sql and 02-menu-export.sql again, and regenerate this script.', v_bad;
  end if;

  -- ------------------------------------------------------------ the plan
  create temp table plan_cat (name text, sort_order int, old_id uuid, action text, station kitchen_station) on commit drop;
  insert into plan_cat values
__CATEGORIES__;

  create temp table plan_item (action text, old_id uuid, cat_name text, name text, price numeric(12,2),
                               visible boolean, sort_order int, description text) on commit drop;
  insert into plan_item values
__ITEMS__;

  -- every planned old item must exist
  select string_agg(p.old_id::text, ', ') into v_bad
  from plan_item p where p.old_id is not null
    and not exists (select 1 from public.menu_items i where i.id = p.old_id);
  if v_bad is not null then
    raise exception 'REFUSED: planned items not found in menu_items: %', v_bad;
  end if;

  -- where each item prints today (before any category changes)
  create temp table old_station on commit drop as
    select i.id, coalesce(i.station, c.station) as station
    from public.menu_items i join public.menu_categories c on c.id = i.category_id;

  select count(*) into v_items_before from public.menu_items;
  select md5(coalesce(string_agg(x::text, E'\n' order by x::text), '')) into v_recipe_md5
    from public.menu_recipe_ingredients x;
  select md5(coalesce(string_agg(x::text, E'\n' order by x::text), '')) into v_internal_md5
    from public.menu_items x
    where x.category_id in (select old_id from plan_cat where action = 'INTERNAL');

  -- ---------------------------------------------------------- categories
  update public.menu_categories c set name = p.name, sort_order = p.sort_order
  from plan_cat p where p.action in ('KEEP', 'RENAME') and c.id = p.old_id;

  insert into public.menu_categories (name, sort_order, station)
  select name, sort_order, station from plan_cat where action = 'CREATE';

  if v_internal_to_end then
    update public.menu_categories c set sort_order = 100 + c.sort_order
    from plan_cat p where p.action = 'INTERNAL' and c.id = p.old_id;
  end if;

  create temp table cat_id on commit drop as
    select p.name, coalesce(p.old_id, c.id) as id
    from plan_cat p left join public.menu_categories c on c.name = p.name and p.old_id is null;

  -- --------------------------------------------------------------- items
  update public.menu_items i
  set name = p.name,
      category_id = k.id,
      selling_price = coalesce(p.price, i.selling_price),
      sort_order = p.sort_order,
      description = p.description,
      is_available = p.visible and p.price is not null,
      is_archived = false
  from plan_item p join cat_id k on k.name = p.cat_name
  where p.action = 'MATCH' and i.id = p.old_id;

  update public.menu_items i
  set category_id = k.id,
      sort_order = p.sort_order,
      is_available = true,
      is_archived = false
  from plan_item p join cat_id k on k.name = p.cat_name
  where p.action = 'KEEP' and i.id = p.old_id;

  update public.menu_items i
  set is_archived = true, is_available = false
  from plan_item p
  where p.action = 'HIDE' and i.id = p.old_id;

  create temp table new_ids (id uuid) on commit drop;
  with ins as (
    insert into public.menu_items (name, category_id, selling_price, sort_order, description, is_available)
    select p.name, k.id, coalesce(p.price, 0), p.sort_order, p.description, p.visible and p.price is not null
    from plan_item p join cat_id k on k.name = p.cat_name
    where p.action = 'NEW'
    returning id
  )
  insert into new_ids select id from ins;

  -- keep every moved item printing where it prints today
  update public.menu_items i
  set station = case when s.station = c.station then null else s.station end
  from old_station s, public.menu_categories c, plan_item p
  where s.id = i.id and c.id = i.category_id and p.old_id = i.id and p.action in ('MATCH', 'KEEP');

  -- ---------------------------------------------------------- self-checks
  select md5(coalesce(string_agg(x::text, E'\n' order by x::text), '')) into v_md5
    from public.menu_recipe_ingredients x;
  if v_md5 <> v_recipe_md5 then
    raise exception 'ABORTED: recipe links changed — rolled back, nothing changed.';
  end if;
  select md5(coalesce(string_agg(x::text, E'\n' order by x::text), '')) into v_md5
    from public.menu_items x
    where x.category_id in (select old_id from plan_cat where action = 'INTERNAL')
      and x.id not in (select old_id from plan_item where action = 'KEEP');
  if v_md5 <> v_internal_md5 then
    raise exception 'ABORTED: an internal-category item changed — rolled back, nothing changed.';
  end if;
  select count(*) into v_n from public.menu_items;
  if v_n <> v_items_before + __N_NEW__ then
    raise exception 'ABORTED: expected % items, found % — rolled back, nothing changed.', v_items_before + __N_NEW__, v_n;
  end if;
  -- visible = matched + new items that are switched on, plus every kept item
  select count(*) into v_n from public.menu_items i
  where (i.id in (select old_id from plan_item where action in ('MATCH', 'KEEP'))
         or i.id in (select id from new_ids))
    and not i.is_archived and i.is_available;
  if v_n <> __N_VISIBLE__ then
    raise exception 'ABORTED: expected __N_VISIBLE__ visible menu items, found % — rolled back, nothing changed.', v_n;
  end if;
  select count(*) into v_n from public.menu_items i
  where i.is_archived and i.id in (select old_id from plan_item where action = 'HIDE');
  if v_n <> __N_HIDE__ then
    raise exception 'ABORTED: expected __N_HIDE__ archived items, found % — rolled back, nothing changed.', v_n;
  end if;

  -- -------------------------------------------------------------- report
  v_report := format(E'\n=== ITEMS === matched %s · new %s · kept %s · archived %s · internal untouched %s',
                     __N_MATCH__, __N_NEW__, __N_KEEP__, __N_HIDE__, __N_INTERNAL__);
  v_report := v_report || format(E'\n=== ON THE POS NOW === %s items', __N_VISIBLE__);
  v_report := v_report || E'\n=== POS TABS (in order) — category · printer · items on POS ===';
  for r in
    select c.name, c.sort_order, c.station,
           count(i.id) filter (where i.is_available and not i.is_archived) as on_pos
    from public.menu_categories c left join public.menu_items i on i.category_id = c.id
    group by c.id, c.name, c.sort_order, c.station
    having count(i.id) filter (where i.is_available and not i.is_archived) > 0
    order by c.sort_order, c.name
  loop
    v_report := v_report || format(E'\n  %2s  %-22s %-8s %s', r.sort_order, r.name, r.station, r.on_pos);
  end loop;
  select string_agg(c.name, ', ' order by c.sort_order) into v_bad
  from public.menu_categories c
  where not exists (select 1 from public.menu_items i where i.category_id = c.id and i.is_available and not i.is_archived);
  v_report := v_report || format(E'\n=== NOT SHOWN ON THE POS (nothing sellable) === %s', coalesce(v_bad, '-'));
  select count(*) into v_n from public.menu_items i join old_station s on s.id = i.id
    join public.menu_categories c on c.id = i.category_id
  where coalesce(i.station, c.station) <> s.station;
  v_report := v_report || format(E'\n=== ITEMS WHOSE PRINTER CHANGED === %s (must be 0)', v_n);
  if v_n <> 0 then
    raise exception 'ABORTED: % items would print somewhere else — rolled back, nothing changed.', v_n;
  end if;

  if not v_commit then
    raise exception E'DRY RUN OK — everything above was rolled back, NOTHING changed.%', v_report
      using hint = 'To apply, set v_commit := true at the top and run again.';
  end if;
  raise notice '%', v_report;
end $$;

-- Reached only when v_commit = true: the new POS menu
select c.sort_order as tab, c.name as category, c.station as printer, i.sort_order as pos,
       i.name as item, i.selling_price as price, i.is_available as on_pos
from public.menu_items i join public.menu_categories c on c.id = i.category_id
where not i.is_archived
order by c.sort_order, c.name, i.sort_order, i.name;
"""

if __name__ == "__main__":
    main()
